from reportlab.lib.pagesizes import A4
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Image
)
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch
import os


def generate_pdf(
    report,
    user,
    output_path
):

    os.makedirs(
        os.path.dirname(output_path),
        exist_ok=True
    )

    doc = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    title = styles["Title"]
    heading = styles["Heading2"]
    normal = styles["BodyText"]

    story = []

    # -----------------------------------------
    # TITLE
    # -----------------------------------------

    story.append(
        Paragraph(
            "BrainScan AI - MRI Analysis Report",
            title
        )
    )

    story.append(
        Spacer(1, 20)
    )


    # -----------------------------------------
    # PATIENT INFORMATION
    # -----------------------------------------

    story.append(
        Paragraph(
            "Patient Information",
            heading
        )
    )

    story.append(
        Spacer(1, 8)
    )

    story.append(
        Paragraph(
            f"<b>Name:</b> {user.name}",
            normal
        )
    )

    story.append(
        Paragraph(
            f"<b>Email:</b> {user.email}",
            normal
        )
    )

    story.append(
        Spacer(1, 15)
    )


    # -----------------------------------------
    # AI RESULT
    # -----------------------------------------

    story.append(
        Paragraph(
            "AI Analysis",
            heading
        )
    )

    story.append(
        Spacer(1, 8)
    )

    story.append(
        Paragraph(
            f"<b>Prediction:</b> "
            f"{report.prediction}",
            normal
        )
    )

    story.append(
        Paragraph(
            f"<b>Confidence:</b> "
            f"{report.confidence:.2f}%",
            normal
        )
    )

    story.append(
        Spacer(1, 15)
    )


    # -----------------------------------------
    # ORIGINAL MRI
    # -----------------------------------------

    image_path = os.path.join(
        "static/uploads",
        report.image
    )

    if os.path.exists(image_path):

        story.append(
            Paragraph(
                "MRI Scan",
                heading
            )
        )

        story.append(
            Spacer(1, 8)
        )

        story.append(
            Image(
                image_path,
                width=4.5 * inch,
                height=4.5 * inch
            )
        )

        story.append(
            Spacer(1, 15)
        )


    # -----------------------------------------
    # GRAD-CAM
    # -----------------------------------------

    if report.gradcam:

        gradcam_path = os.path.join(
            "static/results",
            report.gradcam
        )

        if os.path.exists(gradcam_path):

            story.append(
                Paragraph(
                    "Grad-CAM Visualization",
                    heading
                )
            )

            story.append(
                Spacer(1, 8)
            )

            story.append(
                Image(
                    gradcam_path,
                    width=4.5 * inch,
                    height=4.5 * inch
                )
            )

            story.append(
                Spacer(1, 15)
            )


    # -----------------------------------------
    # AI EXPLANATION
    # -----------------------------------------

    story.append(
        Paragraph(
            "AI Explanation",
            heading
        )
    )

    story.append(
        Spacer(1, 8)
    )

    explanation = f"""
    The ResNet50-based model analyzed the uploaded
    MRI image and classified it as
    <b>{report.prediction}</b> with a confidence
    score of <b>{report.confidence:.2f}%</b>.
    The Grad-CAM visualization provides an
    indication of image regions that influenced
    the model's prediction.
    """

    story.append(
        Paragraph(
            explanation,
            normal
        )
    )

    story.append(
        Spacer(1, 20)
    )


    # -----------------------------------------
    # DISCLAIMER
    # -----------------------------------------

    disclaimer = """
    <b>Medical Disclaimer:</b>
    This report is generated by an artificial
    intelligence system for research and
    educational purposes. It is not a medical
    diagnosis and should not replace evaluation
    by a qualified healthcare professional.
    """

    story.append(
        Paragraph(
            disclaimer,
            normal
        )
    )


    doc.build(story)